  /* Determinístico: cada quadro é desenhado a partir do instante, não gravado
     enquanto a animação roda — o mesmo vídeo em máquina lenta ou rápida. */
  function gerarMP4(base, op, aviso, cancelado) {
    aviso = aviso || function () {}; cancelado = cancelado || function () { return false; };
    var cena, r, enc = null, cv = null, erroEnc = null;
    try { cena = preparar(base, op); } catch (e) { return Promise.reject(e); }
    if (!cena.daas.length) return Promise.reject(Object.assign(new Error('sem-datas'), { codigo: 'noDates' }));
    r = roteiro(cena.daas);
    /* giro lento: 8° no vídeo inteiro, centrado onde a pessoa deixou a câmera */
    var amp = 8 * Math.PI / 180;
    cena.rots = [cena.rot0 - amp / 2, cena.rot0, cena.rot0 + amp / 2];
    aviso({ fase: 'preparing' });
    return escolherCodec().then(function (cfg) {
      if (!cfg) throw Object.assign(new Error('sem-h264'), { codigo: 'videoUnsupported' });
      return carregarMuxer().then(function (M) {
        var muxer = new M.Muxer({ target: new M.ArrayBufferTarget(), video: { codec: 'avc', width: W, height: H, frameRate: FPS },
          fastStart: 'in-memory', firstTimestampBehavior: 'offset' });
        enc = new w.VideoEncoder({ output: function (ch, meta) { muxer.addVideoChunk(ch, meta); }, error: function (e) { erroEnc = e; } });
        enc.configure(cfg);
        cv = novoCanvas();
        var ctx = cv.getContext('2d'), f = 0, dur = Math.round(1e6 / FPS);
        function lote() {
          if (cancelado()) throw Object.assign(new Error('cancelado'), { codigo: 'canceled' });
          if (erroEnc) throw erroEnc;
          var fim = Math.min(r.quadros, f + 6);
          for (; f < fim; f++) {
            var q = instante(r, f);
            q.rot = cena.rot0 + (q.progresso - 0.5) * amp;
            compor(ctx, cena, q);
            var vf = new w.VideoFrame(cv, { timestamp: f * dur, duration: dur });
            try { enc.encode(vf, { keyFrame: f % (FPS * 2) === 0 }); } finally { vf.close(); }
          }
          aviso({ fase: 'rendering', pct: Math.round(100 * f / r.quadros) });
          var espera = function () { return enc.encodeQueueSize > 12 ? new Promise(function (ok) { setTimeout(ok, 8); }).then(espera) : tique(); };
          return espera().then(function () { return f < r.quadros ? lote() : null; });
        }
        return lote().then(function () {
          aviso({ fase: 'encoding' });
          return enc.flush();
        }).then(function () {
          if (erroEnc) throw erroEnc;
          muxer.finalize();
          var blob = new Blob([muxer.target.buffer], { type: 'video/mp4' });
          var rot = cena.daas.length > 1 ? num(cena.daas[0], 0, 'en') + '-' + num(cena.daas[cena.daas.length - 1], 0, 'en') + 'DAA' : num(cena.daas[0], 0, 'en') + 'DAA';
          return { blob: blob, nome: nomeArquivo(cena.codigo, cena.variavel, rot, 'mp4'), quadros: r.quadros, segundos: r.segundos, codec: cfg.codec };
        });
      });
    }).then(function (res) { limpar(); return res; }, function (e) { limpar(); throw e; });
    function limpar() {
      if (enc && enc.state !== 'closed') { try { enc.close(); } catch (e) {} }
      if (cv) liberarCanvas(cv);
      enc = null; cv = null;
    }
  }

